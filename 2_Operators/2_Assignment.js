// 2. Assignment Operators (+=, -=, *=, /=, %=, **=)
let x=10;
x+=15;
console.log(x); // x=10+15=25

x-=16;
console.log(x); // x=25-16=9

x*=8;
console.log(x); // x=9*8=72

x/=3;
console.log(x); // x=72/3=24

let y=25;
y%=2;
console.log(y); // y=25%2=1 (remainder)

let z=3; z**=4;
console.log(z); // z=3^4=3*3*3*3=81