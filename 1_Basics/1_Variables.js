// Variables in JS (Var, Let and Const)
// 1. Var
var a=10;
console.log(a);
var a=25;  //we can redeclare variable by var.
console.log(a);

console.log("=========================");

// 2.Let
let b=15;
console.log(b);
// let b=25 ---error
b=20;
console.log(b);

console.log("=========================");

// 3.Const
const c=35;
console.log(c);
// const c=50; ---error
// c=26; ---error